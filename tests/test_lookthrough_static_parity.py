def test_golden_book_parity(fixture_blob):
    """Whole books, every weight, at 1e-12."""
    out = _run_js(
        """
const results = [];
for (const g of fixture.golden) {
  let r;
  try { r = engine.lookThrough(g.input); }
  catch (e) { r = {threw: String(e && e.message || e)}; }
  results.push({label: g.label, got: r});
}
console.log(JSON.stringify(results));
"""
    )
    by_label = {r["label"]: r["got"] for r in out}
    problems: list[str] = []

    for g in fixture_blob["golden"]:
        label, exp = g["label"], g["expect"]
        got = by_label.get(label)
        if got is None:
            problems.append(f"[{label}] JS produced no result")
            continue
        if got.get("threw"):
            problems.append(f"[{label}] JS threw: {got['threw']}")
            continue

        if bool(got.get("computed")) != bool(exp["computed"]):
            problems.append(
                f"[{label}] computed: python={exp['computed']} js={got.get('computed')} "
                f"(js reason: {got.get('not_computed_reason')!r})"
            )
            continue
        if not exp["computed"]:
            continue

        for key in ("n_listed", "n_unpacked", "n_companies"):
            if got.get(key) != exp[key]:
                problems.append(f"[{label}] {key}: python={exp[key]} js={got.get(key)}")

        py_lines = {ln["symbol"]: ln for ln in exp["lines"]}
        js_lines = {ln["symbol"]: ln for ln in got.get("rows", [])}

        only_py = sorted(set(py_lines) - set(js_lines))
        only_js = sorted(set(js_lines) - set(py_lines))
        if only_py:
            problems.append(f"[{label}] python has holdings JS does not: {only_py[:10]}")
        if only_js:
            problems.append(f"[{label}] JS invented holdings python does not have: {only_js[:10]}")

        for sym in sorted(set(py_lines) & set(js_lines)):
            p, j = py_lines[sym], js_lines[sym]
            if abs(float(p["actual"]) - float(j["actual"])) > TOL:
                problems.append(f"[{label}] {sym} actual: python={p['actual']!r} js={j['actual']!r}")
            pl, jl = p["listed"], j["listed"]
            if (pl is None) != (jl is None):
                problems.append(f"[{label}] {sym} listed presence: python={pl!r} js={jl!r}")
            elif pl is not None and abs(float(pl) - float(jl)) > TOL:
                problems.append(f"[{label}] {sym} listed: python={pl!r} js={jl!r}")
            if p["kind"] != j["kind"]:
                problems.append(f"[{label}] {sym} kind: python={p['kind']!r} js={j['kind']!r}")

    assert not problems, "the static page computes different numbers:\n" + "\n".join("  " + p for p in problems)


def test_js_never_unpacks_what_python_refused(fixture_blob):
    """The permitted divergence has ONE direction, and this is it.

    The JS has no AMFI master, so it may refuse a fund Python resolved. It
    must never do the opposite: unpacking a fund Python left alone, or
    unpacking it into a different index, puts companies in the reader's
    portfolio that are not there and reports success doing it.
    """
    out = _run_js(
        """
const results = [];
for (const g of fixture.golden) {
  let r;
  try { r = engine.lookThrough(g.input); } catch (e) { r = {funds: []}; }
  results.push({label: g.label, funds: r.funds || []});
}
console.log(JSON.stringify(results));
"""
    )
    by_label = {r["label"]: r["funds"] for r in out}
    problems: list[str] = []

    for g in fixture_blob["golden"]:
        if not g["expect"]["computed"]:
            continue
        py = {f["label"].upper(): f for f in g["expect"]["funds"]}
        js = {f["label"].upper(): f for f in by_label.get(g["label"], [])}
        for key, jf in js.items():
            pf = py.get(key)
            if pf is None:
                continue
            if jf["unpacked"] and not pf["unpacked"]:
                problems.append(
                    f"[{g['label']}] {key}: JS unpacked a fund python refused (JS index={jf.get('index')!r})"
                )
            if jf["unpacked"] and pf["unpacked"] and jf.get("index") != pf.get("index"):
                problems.append(
                    f"[{g['label']}] {key}: index disagreement python={pf.get('index')!r} js={jf.get('index')!r}"
                )

    assert not problems, "the static page over-claims:\n" + "\n".join("  " + p for p in problems)


