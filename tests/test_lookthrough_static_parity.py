def test_index_phrase_parity(fixture_blob):
    """Python's index_phrase and the JS port must agree on every row."""
    out = _run_js(
        """
const bad = [];
for (const row of fixture.parity.rows) {
  const got = engine.indexPhrase(row.text);
  if (got !== row.phrase) bad.push({text: row.text, py: row.phrase, js: got});
}
console.log(JSON.stringify({n: fixture.parity.rows.length, bad: bad.slice(0, 25), nbad: bad.length}));
"""
    )
    assert out["nbad"] == 0, (
        f"{out['nbad']} of {out['n']} names reduce differently in JS than in Python.\n"
        + "\n".join(f"  {b['text']!r}\n    python={b['py']!r}\n    js    ={b['js']!r}" for b in out["bad"])
    )


def test_classify_parity(fixture_blob):
    """index / active / unknown must agree on every row.

    Classification decides whether the reader is told "a manager picks these"
    or "this tracks an index we do not hold a list for". Those are different
    sentences about their money.
    """
    out = _run_js(
        """
const bad = [];
for (const row of fixture.parity.rows) {
  const got = engine.classify(row.text, row.category);
  if (got !== row.classification) bad.push({text: row.text, cat: row.category, py: row.classification, js: got});
}
console.log(JSON.stringify({n: fixture.parity.rows.length, bad: bad.slice(0, 25), nbad: bad.length}));
"""
    )
    assert out["nbad"] == 0, f"{out['nbad']} of {out['n']} names classify differently.\n" + "\n".join(
        f"  {b['text']!r} (cat={b['cat']!r}) python={b['py']!r} js={b['js']!r}" for b in out["bad"]
    )


