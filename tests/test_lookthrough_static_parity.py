def test_fixture_matches_the_shipped_data(fixture_blob, page_blob):
    """A stale fixture would prove the JS agrees with numbers nobody ships."""
    assert fixture_blob["generated"] == page_blob["generated"], (
        "the parity fixture and the page data were generated on different days; "
        "re-run scripts/export_lookthrough_data.py so both come from one export"
    )


def test_page_data_carries_no_test_corpus(page_blob):
    """The 690 KB of test evidence must not be sent to every visitor."""
    assert "parity" not in page_blob
    assert "golden" not in page_blob
    assert PAGE_DATA.stat().st_size < 400_000, (
        f"page data is {PAGE_DATA.stat().st_size:,} bytes — something large leaked into it"
    )


def test_every_exported_index_sums_to_one(page_blob):
    """Every figure on the page is a share of this, so it cannot be 0.97."""
    for name, blob in page_blob["indices"].items():
        total = sum(blob["weights"].values())
        assert abs(total - 1.0) < 1e-9, f"{name} weights sum to {total!r}"


def test_an_excluded_constituent_is_recorded_not_silently_dropped(page_blob):
    """NIFTY 500 drops names Yahoo has no cap for; the reason must survive.

    The weights are renormalised over what is left, which is the honest
    handling — but only if the omission is stated. A reader comparing our
    497 against NSE's 501 deserves the reason, not a discrepancy.
    """
    for name, blob in page_blob["indices"].items():
        for entry in blob["excluded"]:
            assert len(entry) == 2 and entry[1].strip(), f"{name} excluded {entry[0]} without a reason"


