"""The JS look-through must give the SAME answer as the Python one.

WHY THIS FILE IS THE WHOLE ARGUMENT
    ``products/site/lookthrough.js`` is a second implementation of a
    calculation this repo already has in Python. Two implementations of one
    calculation is the most reliable way to end up with two answers to one
    question, and most of ``LESSONS.md`` is variations on that theme. The
    static page is only defensible if the agreement is *proven on every
    build* rather than believed.

    So this file drives the JS under node over fixtures generated BY the
    Python, and requires exact agreement:

    * ``test_index_phrase_parity`` / ``test_classify_parity`` — every scheme
      name in the live AMFI master (3,400+ distinct names), plus the ticker
      tables and the paste shapes a user actually types. ``index_phrase`` is
      a lossy reduction tuned over real Indian scheme names; a port that
      agrees on twenty hand-picked examples proves nothing, and one that
      agrees on three thousand is a port.
    * ``test_golden_book_parity`` — whole books through the real engine, with
      every weight compared at 1e-12. This is the arithmetic the headline is
      made of.

    A failure here means the page is showing a different number from the
    server and must not ship. It is not a flaky-test problem to route around.

WHAT IS DELIBERATELY *NOT* ASSERTED
    The JS resolver is NARROWER than Python's: the server also consults
    AMFI's scheme master by ISIN and by exact name (14,000 schemes, far too
    large to send to a browser), which gives it AMFI's own SEBI category.
    The JS resolves on the typed text alone.

    That difference is one-directional and the tests pin the direction: the
    JS may REFUSE a fund Python would have unpacked, and must never unpack
    one Python refused, nor unpack it into a different index. A refusal the
    reader can see is recoverable; a wrong unpack reports success while
    being wrong, which is the failure this product cannot survive.
    ``test_js_never_unpacks_what_python_refused`` is that check.

REGENERATING
    PYTHONPATH=. .venv/bin/python scripts/export_lookthrough_data.py

    The fixture and the page data carry the same ``generated`` date;
    ``test_fixture_matches_the_shipped_data`` fails if they drift, because a
    stale fixture would validate a page built from different numbers.
"""

from __future__ import annotations

import gzip
import json
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
PAGE_DATA = REPO / "products/site/data/lookthrough.json"
FIXTURE = REPO / "tests/fixtures/lookthrough_parity.json.gz"
JS = REPO / "products/site/lookthrough.js"

#: Weights are compared at this tolerance. It is tight on purpose: a looser
#: one would hide the slow drift this file exists to catch, and both sides are
#: IEEE doubles doing the same multiplications, so they have no excuse to
#: differ at all.
TOL = 1e-12

pytestmark = pytest.mark.skipif(
    shutil.which("node") is None,
    reason="node is not installed, so the JS cannot be executed to compare it",
)


def _require_artifacts() -> None:
    missing = [p for p in (PAGE_DATA, FIXTURE, JS) if not p.is_file()]
    if missing:
        pytest.fail(
            "missing "
            + ", ".join(str(p.relative_to(REPO)) for p in missing)
            + " — run: PYTHONPATH=. .venv/bin/python scripts/export_lookthrough_data.py"
        )


def _run_js(script: str) -> object:
    """Execute a node snippet with the engine loaded, return its JSON stdout."""
    _require_artifacts()
    prelude = f"""
const zlib = require("zlib");
const fs = require("fs");
const LT = require({json.dumps(str(JS))});
const data = require({json.dumps(str(PAGE_DATA))});
// The fixture ships gzipped; node inflates it rather than keeping a second
// uncompressed copy on disk that could drift from the compressed one.
const fixture = JSON.parse(zlib.gunzipSync(fs.readFileSync({json.dumps(str(FIXTURE))})).toString("utf8"));
const engine = new LT.Engine(data);
"""
    proc = subprocess.run(
        ["node", "-e", prelude + script],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=str(REPO),
    )
    if proc.returncode != 0:
        pytest.fail(f"node exited {proc.returncode}\nSTDERR:\n{proc.stderr}\nSTDOUT:\n{proc.stdout[:2000]}")
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        pytest.fail(f"node did not emit JSON ({exc})\nSTDOUT:\n{proc.stdout[:2000]}\nSTDERR:\n{proc.stderr[:2000]}")


@pytest.fixture(scope="module")
def fixture_blob() -> dict:
    _require_artifacts()
    with gzip.open(FIXTURE, "rt", encoding="utf-8") as fh:
        return json.load(fh)


@pytest.fixture(scope="module")
def page_blob() -> dict:
    _require_artifacts()
    return json.loads(PAGE_DATA.read_text(encoding="utf-8"))


