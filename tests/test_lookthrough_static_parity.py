@pytest.mark.parametrize(
    "book, expect_in_reason",
    [
        ("HDFCBANK 100 units\nRELIANCE 50 units", "share counts"),
        ("HDFCBANK 1,20,000\nRELIANCE 50000", "Indian digit grouping"),
        ("HDFCBANK 2 crore\nRELIANCE 1 crore", "crore"),
        ("", "nothing was pasted"),
    ],
)
def test_shapes_the_page_refuses_rather_than_guesses(book, expect_in_reason):
    """Each of these has a plausible wrong reading, which is why it is refused.

    "1,20,000" is 120000 to an Indian reader and 1.2 to a naive parser;
    guessing produces a confidently wrong headline, so the page says what to
    change instead.
    """
    out = _run_js(
        f"""
let r;
try {{ r = engine.lookThrough({json.dumps(book)}); }}
catch (e) {{ r = {{computed: false, not_computed_reason: "threw: " + String(e && e.message || e)}}; }}
console.log(JSON.stringify(r));
"""
    )
    assert out["computed"] is False, f"expected a refusal for {book!r}, got a computed answer"
    reason = out.get("not_computed_reason") or ""
    assert expect_in_reason.lower() in reason.lower(), f"reason {reason!r} does not mention {expect_in_reason!r}"


def test_a_refusal_always_says_what_to_change():
    """A refusal with no instruction is a dead end the reader cannot leave."""
    out = _run_js(
        """
const books = [
  "HDFCBANK 100 units",
  "HDFCBANK 1,20,000",
  "HDFCBANK 2 lakh",
  "",
  "   \\n  \\n ",
  "no number here",
];
const out = [];
for (const b of books) {
  let r;
  try { r = engine.lookThrough(b); } catch (e) { r = {computed: false, not_computed_reason: ""}; }
  if (r.computed !== true) out.push({book: b, reason: r.not_computed_reason || ""});
}
console.log(JSON.stringify(out));
"""
    )
    for row in out:
        assert row["reason"].strip(), f"refused {row['book']!r} with an empty reason"


def test_no_advice_language_in_any_string_the_page_produces():
    """This product is an audit. Advice is regulated, and we do not give it."""
    from agent.portfolio import audit as A

    out = _run_js(
        """
const books = [
  "HDFCBANK 12%\\nNIFTYBEES 40%\\nGOLDBEES 18%\\nParag Parikh Flexi Cap Fund 30%",
  "HDFCBANK 100 units",
  "NIFTYBEES 100%",
  "",
];
const strings = [];
function walk(o) {
  if (typeof o === "string") strings.push(o);
  else if (Array.isArray(o)) o.forEach(walk);
  else if (o && typeof o === "object") Object.keys(o).forEach(k => walk(o[k]));
}
for (const b of books) {
  let r;
  try { r = engine.lookThrough(b); } catch (e) { r = {}; }
  walk(r);
}
console.log(JSON.stringify(strings));
"""
    )
    offenders = [(s, A.advice_words_in(s)) for s in out if A.advice_words_in(s)]
    assert not offenders, "advice language on the static page:\n" + "\n".join(
        f"  {words!r} in {s!r}" for s, words in offenders
    )
